//! Preset record lengths translated from pinned n64decomp/sm64 (CC0).
//! See include/special_presets.h, include/special_presets.inc.c, and PROVENANCE.md.
pub(crate) fn extra_words(preset: u8) -> Option<usize> {
    match preset {
        0x01 | 0x02 | 0x03 | 0x04 | 0x05 | 0x06 | 0x07 | 0x09 | 0x0A | 0x0B | 0x0C | 0x0D
        | 0x0F | 0x10 | 0x11 | 0x12 | 0x13 | 0x14 | 0x15 | 0x16 | 0x17 | 0x18 | 0x19 | 0x1A
        | 0x1B | 0x1C | 0x1D | 0x1F | 0x20 | 0x21 | 0x22 | 0x25 | 0x26 | 0x27 | 0x28 | 0x79
        | 0x7A | 0x7B | 0x7C | 0x7D | 0xFF => Some(0),
        0x00 | 0x08 | 0x0E | 0x23 | 0x24 | 0x65 | 0x66 | 0x67 | 0x68 | 0x69 | 0x6A | 0x6B
        | 0x6C | 0x6D | 0x6E | 0x6F | 0x70 | 0x71 | 0x72 | 0x73 | 0x74 | 0x75 | 0x76 | 0x77
        | 0x78 | 0x7E | 0x7F | 0x80 | 0x81 | 0x82 | 0x89 | 0x8A | 0x8B | 0x8C | 0x8D => Some(1),
        0x83..=0x88 => Some(2),
        0x1E => Some(3),
        _ => None,
    }
}
